#!/usr/bin/env bash
set -euo pipefail

# M2 release artifacts are additive: an existing artifact is evidence to inspect,
# never something this script removes or replaces.
root_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
dist_dir="${root_dir}/dist"
package_dist_dir="${root_dir}/package-dist"
package_marker=".cockpit-mux-package-stage"
sha256_of() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | awk '{print $1}'
  else
    shasum -a 256 "$1" | awk '{print $1}'
  fi
}

source_hash="$({
  while IFS= read -r -d '' source; do
    printf '%s:%s\n' "${source#"${root_dir}"/}" "$(sha256_of "${source}")"
  done < <(find "${root_dir}" \
    \( -path "${root_dir}/.build" -o -path "${dist_dir}" -o -path "${package_dist_dir}" \) -prune -o \
    -type f \( \( -name '*.go' ! -name '*_test.go' \) -o -name 'go.mod' -o -name 'go.sum' -o -path '*/daemon/assets/*' \) -print0 | LC_ALL=C sort -z)

  # libghostty-vt is statically linked into every mux binary. Its pinned
  # revision and target build arguments therefore belong to the artifact's
  # identity even though the Ghostty checkout itself remains an external,
  # provisioned dependency rather than an archived source input.
  for source in "${root_dir}/Makefile" "${root_dir}/scripts/build-artifacts.sh" "${root_dir}/scripts/build-libghostty-vt.sh"; do
    printf '%s:%s\n' "${source#"${root_dir}"/}" "$(sha256_of "${source}")"
  done
} | {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum | awk '{print $1}'; else shasum -a 256 | awk '{print $1}'; fi
})"

stage_package_artifacts() {
  local source_manifest="$1"
  local stage_dir
  local artifact
  local staged_count=0

  stage_dir="$(mktemp -d "${root_dir}/.package-dist.XXXXXX")"
  cp "${source_manifest}" "${stage_dir}/"
  while IFS= read -r artifact; do
    [[ -n "${artifact}" ]] || continue
    cp "${dist_dir}/${artifact}" "${stage_dir}/${artifact}"
    ((staged_count += 1))
  done < <(grep -o '"filename":"[^"]*"' "${source_manifest}" | sed 's/^"filename":"//; s/"$//')
  if (( staged_count != 4 )); then
    echo "refusing to stage malformed mux manifest: ${source_manifest}" >&2
    exit 1
  fi
  printf '%s\n' "generated by cockpit-mux/scripts/build-artifacts.sh" > "${stage_dir}/${package_marker}"
  printf '%s\n' "${source_hash}" > "${stage_dir}/source-hash"

  if [[ -e "${package_dist_dir}" ]]; then
    if [[ ! -f "${package_dist_dir}/${package_marker}" ]]; then
      echo "refusing to replace non-generated mux package stage: ${package_dist_dir}" >&2
      exit 1
    fi
    rm -rf "${package_dist_dir}"
  fi
  mv "${stage_dir}" "${package_dist_dir}"
}

mkdir -p "${dist_dir}"
for existing_manifest in "${dist_dir}"/manifest-*.json; do
  [[ -f "${existing_manifest}" ]] || continue
  if grep -Fq "\"sourceHash\": \"${source_hash}\"" "${existing_manifest}"; then
    echo "preserving current mux artifact set: ${existing_manifest}" >&2
    stage_package_artifacts "${existing_manifest}"
    exit 0
  fi
done

if [[ -n "${VERSION:-}" ]]; then
  version="${VERSION}"
else
  latest_major=0
  latest_minor=0
  latest_patch=-1
  for existing_artifact in "${dist_dir}"/*; do
    [[ -e "${existing_artifact}" ]] || continue
    filename="${existing_artifact##*/}"
    if [[ "${filename}" =~ ^manifest-([0-9]+)\.([0-9]+)\.([0-9]+)\.json$ ]] || [[ "${filename}" =~ ^cockpit-mux-([0-9]+)\.([0-9]+)\.([0-9]+)-(darwin|linux)-(arm64|amd64)$ ]]; then
      major="${BASH_REMATCH[1]}"
      minor="${BASH_REMATCH[2]}"
      patch="${BASH_REMATCH[3]}"
      if (( major > latest_major || (major == latest_major && minor > latest_minor) || (major == latest_major && minor == latest_minor && patch > latest_patch) )); then
        latest_major="${major}"
        latest_minor="${minor}"
        latest_patch="${patch}"
      fi
    fi
  done
  version="${latest_major}.${latest_minor}.$((latest_patch + 1))"
fi
manifest_path="${dist_dir}/manifest-${version}.json"
if [[ -e "${manifest_path}" ]]; then
  echo "refusing to replace existing mux manifest: ${manifest_path}" >&2
  exit 1
fi

# Build into a private staging directory. A failed cross-build must never leave
# a partially published artifact set in dist/, where it would be indistinguish-
# able from an interrupted release that needs investigation.
artifact_stage_dir="$(mktemp -d "${root_dir}/.artifact-build.XXXXXX")"
cleanup_artifact_stage() {
  rm -rf "${artifact_stage_dir}"
}
trap cleanup_artifact_stage EXIT

targets=("darwin arm64 native" "darwin amd64 x86_64-macos" "linux amd64 x86_64-linux-musl" "linux arm64 aarch64-linux-musl")
entries=()
for target in "${targets[@]}"; do
  read -r os arch ghostty_target <<<"${target}"
  filename="cockpit-mux-${version}-${os}-${arch}"
  artifact="${dist_dir}/${filename}"
  if [[ -e "${artifact}" ]]; then
    # A version without a matching manifest has no proven source identity. Do
    # not overwrite or silently publish it under this build's new hash.
    echo "refusing unmanifested mux artifact: ${artifact}; inspect it or choose a new VERSION" >&2
    exit 1
  fi
  staged_artifact="${artifact_stage_dir}/${filename}"
  make_args=(-C "${root_dir}" build-artifact GOOS="${os}" GOARCH="${arch}" VERSION="${version}" SOURCE_HASH="${source_hash}" LIBGHOSTTY_TARGET="${ghostty_target}" ARTIFACT="${staged_artifact}")
  target_cache="${root_dir}/.build/go-cache/${os}-${arch}"
  if [[ "${os}" == "linux" ]]; then
    GOCACHE="${target_cache}" CC="zig cc -target ${ghostty_target}" make "${make_args[@]}"
  else
    GOCACHE="${target_cache}" make "${make_args[@]}"
  fi
  sum="$(sha256_of "${staged_artifact}")"
  entries+=("{\"os\":\"${os}\",\"arch\":\"${arch}\",\"filename\":\"${filename}\",\"sha256\":\"${sum}\"}")
done
joined="$(IFS=,; echo "${entries[*]}")"
printf '{\n  "version": "%s",\n  "sourceHash": "%s",\n  "binaries": [%s]\n}\n' "${version}" "${source_hash}" "${joined}" > "${artifact_stage_dir}/manifest-${version}.json"

for target in "${targets[@]}"; do
  read -r os arch _ <<<"${target}"
  filename="cockpit-mux-${version}-${os}-${arch}"
  artifact="${dist_dir}/${filename}"
  if [[ -e "${artifact}" ]]; then
    echo "refusing concurrent mux artifact publication: ${artifact}" >&2
    exit 1
  fi
  mv "${artifact_stage_dir}/${filename}" "${artifact}"
done
mv "${artifact_stage_dir}/manifest-${version}.json" "${manifest_path}"
stage_package_artifacts "${manifest_path}"
